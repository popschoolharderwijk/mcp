import { dedupeImportRowsByUserId } from '../shared/dedupeImportRowsByUserIdHelpers';
import { sqlDate, sqlUuid } from '../shared/sqlEscapeHelpers';
import type { MappedStudentRow } from './types';

export type StudentSqlRow = MappedStudentRow & { userId: string };

/** Role-only SQL: public.students (auth user must already exist from profiles.sql). */
export function buildStudentsSql(rows: StudentSqlRow[]): string {
	if (rows.length === 0) {
		return '-- No students to import\n';
	}

	const deduped = dedupeImportRowsByUserId(rows, (existing, duplicate) => ({
		...existing,
		dateOfBirth: existing.dateOfBirth ?? duplicate.dateOfBirth,
	}));

	const valueTuples = deduped.map((row) => `    (${sqlUuid(row.userId)}, ${sqlDate(row.dateOfBirth)})`).join(',\n');

	return `-- Generated by import/students — public.students only (run after profiles.sql).
DO $$
DECLARE
  n integer;
BEGIN
  CREATE TEMP TABLE mongo_import_students (
    id UUID PRIMARY KEY,
    date_of_birth DATE
  ) ON COMMIT DROP;

  INSERT INTO mongo_import_students (id, date_of_birth)
  VALUES
${valueTuples};

  INSERT INTO public.students (user_id, date_of_birth)
  SELECT id, date_of_birth
  FROM mongo_import_students
  ON CONFLICT (user_id) DO UPDATE SET
    date_of_birth = EXCLUDED.date_of_birth,
    updated_at = now();
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'public.students: % row(s) upserted', n;
END $$;
`;
}
