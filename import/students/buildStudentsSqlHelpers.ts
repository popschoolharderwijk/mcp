import { sqlDate, sqlString, sqlUuid } from '../shared/sqlEscapeHelpers';
import type { MappedStudentRow } from './types';

/** Same bcrypt hash as supabase/seeds/test.sql (password "password"); accounts use magic link later. */
const SEED_ENCRYPTED_PASSWORD = '$2a$10$9e974vMhtRxGA42trytRd.tC0yXzEhsKO0xN8lgoLjy5psvhsJTY.';

export type StudentSqlRow = MappedStudentRow & { userId: string };

export function buildStudentsSql(rows: StudentSqlRow[]): string {
	if (rows.length === 0) {
		return '-- No students to import\n';
	}

	const valueTuples = rows
		.map((row) => {
			return `    (${sqlUuid(row.userId)}, ${sqlString(row.email)}, ${sqlString(row.firstName)}, ${sqlString(row.lastName)}, ${sqlString(row.phoneNumber)}, ${sqlString(row.streetName)}, ${sqlString(row.houseNumber)}, ${sqlString(row.postalCode)}, ${sqlString(row.city)}, ${sqlString(row.countryCode)}, ${sqlDate(row.dateOfBirth)})`;
		})
		.join(',\n');

	return `-- Generated by import/students — apply manually to the target database.
DO $$
DECLARE
  n integer;
BEGIN
  CREATE TEMP TABLE mongo_import_students (
    id UUID PRIMARY KEY,
    email TEXT NOT NULL,
    first_name TEXT,
    last_name TEXT,
    phone_number TEXT,
    street_name TEXT,
    house_number TEXT,
    postal_code TEXT,
    city TEXT,
    country_code TEXT NOT NULL DEFAULT 'NL',
    date_of_birth DATE
  ) ON COMMIT DROP;

  INSERT INTO mongo_import_students (id, email, first_name, last_name, phone_number, street_name, house_number, postal_code, city, country_code, date_of_birth)
  VALUES
${valueTuples};

  INSERT INTO auth.users (
    id,
    instance_id,
    aud,
    role,
    email,
    encrypted_password,
    email_confirmed_at,
    raw_app_meta_data,
    raw_user_meta_data,
    created_at,
    updated_at,
    confirmation_token,
    email_change,
    email_change_token_new,
    recovery_token
  )
  SELECT
    id,
    '00000000-0000-0000-0000-000000000000',
    'authenticated',
    'authenticated',
    email,
    '${SEED_ENCRYPTED_PASSWORD}',
    now(),
    '{"provider":"email","providers":["email"]}',
    json_build_object(
      'first_name', first_name,
      'last_name', last_name
    ),
    now(),
    now(),
    '',
    '',
    '',
    ''
  FROM mongo_import_students
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    raw_user_meta_data = EXCLUDED.raw_user_meta_data,
    updated_at = now();
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'auth.users: % row(s) upserted', n;

  INSERT INTO auth.identities (
    id,
    user_id,
    provider_id,
    provider,
    identity_data,
    last_sign_in_at,
    created_at,
    updated_at
  )
  SELECT
    id,
    id,
    email,
    'email',
    json_build_object(
      'sub', id::text,
      'email', email,
      'email_verified', true,
      'provider', 'email'
    ),
    now(),
    now(),
    now()
  FROM mongo_import_students
  ON CONFLICT (id) DO NOTHING;
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'auth.identities: % row(s) inserted', n;

  UPDATE public.profiles p
  SET
    first_name = s.first_name,
    last_name = s.last_name,
    phone_number = s.phone_number,
    email = s.email,
    street_name = s.street_name,
    house_number = s.house_number,
    postal_code = s.postal_code,
    city = s.city,
    country_code = s.country_code
  FROM mongo_import_students s
  WHERE p.user_id = s.id;
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'public.profiles: % row(s) updated', n;

  INSERT INTO public.students (user_id, date_of_birth)
  SELECT id, date_of_birth
  FROM mongo_import_students
  ON CONFLICT (user_id) DO UPDATE SET
    date_of_birth = EXCLUDED.date_of_birth,
    updated_at = now();
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'public.students: % row(s) upserted', n;
END $$;
`;
}
