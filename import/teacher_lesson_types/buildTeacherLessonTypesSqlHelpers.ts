import { sqlUuid } from '../shared/sqlEscapeHelpers';
import type { TeacherLessonTypeSqlRow } from './types';

/** Deduplicate links (same teacher+lesson type from many agreements). */
export function dedupeTeacherLessonTypeRows(rows: readonly TeacherLessonTypeSqlRow[]): TeacherLessonTypeSqlRow[] {
	const seen = new Set<string>();
	const unique: TeacherLessonTypeSqlRow[] = [];
	for (const row of rows) {
		const key = `${row.teacherUserId}:${row.lessonTypeId}`;
		if (seen.has(key)) continue;
		seen.add(key);
		unique.push(row);
	}
	unique.sort((a, b) => {
		const byTeacher = a.teacherUserId.localeCompare(b.teacherUserId);
		if (byTeacher !== 0) return byTeacher;
		return a.lessonTypeId.localeCompare(b.lessonTypeId);
	});
	return unique;
}

/** Idempotent INSERT into public.teacher_lesson_types. */
export function buildTeacherLessonTypesSql(rows: TeacherLessonTypeSqlRow[]): string {
	const unique = dedupeTeacherLessonTypeRows(rows);
	if (unique.length === 0) {
		return '-- No teacher_lesson_types to import\n';
	}

	const tuples = unique.map((row) => `  (${sqlUuid(row.teacherUserId)}, ${sqlUuid(row.lessonTypeId)})`).join(',\n');

	return `-- Generated by import/teacher_lesson_types — links from agreements_course + teachers.
DO $$
DECLARE
  n integer;
BEGIN
  INSERT INTO public.teacher_lesson_types (teacher_user_id, lesson_type_id)
  SELECT v.teacher_user_id, v.lesson_type_id
  FROM (VALUES
${tuples}
  ) AS v(teacher_user_id, lesson_type_id)
  WHERE NOT EXISTS (
    SELECT 1 FROM public.teacher_lesson_types tlt
    WHERE tlt.teacher_user_id = v.teacher_user_id
      AND tlt.lesson_type_id = v.lesson_type_id
  );
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'public.teacher_lesson_types: % row(s) inserted (existing skipped)', n;
END $$;
`;
}
