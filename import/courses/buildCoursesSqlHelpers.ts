import { sqlBoolean, sqlInteger, sqlNumber, sqlString, sqlUuid } from '../shared/sqlEscapeHelpers';
import type { CourseSqlRow } from './types';

function buildLessonTypesInsert(rows: CourseSqlRow[]): string {
	const tuples = rows
		.map((row) => {
			return `  (${sqlUuid(row.lessonTypeId)}, ${sqlString(row.name)}, NULL, ${sqlString(row.icon)}, ${sqlString(row.color)}, ${sqlString(row.costCenter)}, ${sqlBoolean(row.isGroupLesson)}, ${sqlBoolean(row.isDuoLesson)}, ${sqlBoolean(true)})`;
		})
		.join(',\n');

	return `  -- Lesson types (from Mongo courses export)
  INSERT INTO public.lesson_types (id, name, description, icon, color, cost_center, is_group_lesson, is_duo_lesson, is_active)
  SELECT v.id, v.name, v.description, v.icon, v.color, v.cost_center, v.is_group_lesson, v.is_duo_lesson, v.is_active
  FROM (VALUES
${tuples}
  ) AS v(id, name, description, icon, color, cost_center, is_group_lesson, is_duo_lesson, is_active)
  WHERE NOT EXISTS (SELECT 1 FROM public.lesson_types WHERE lesson_types.name = v.name);
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'public.lesson_types: % row(s) inserted (existing skipped)', n;
`;
}

function buildLessonTypeOptionsInsert(rows: CourseSqlRow[]): string {
	const optionTuples: string[] = [];
	for (const row of rows) {
		for (const opt of row.options) {
			optionTuples.push(
				`  (${sqlString(row.name)}, ${sqlInteger(opt.durationMinutes)}, '${opt.frequency}'::public.lesson_frequency, ${sqlNumber(opt.pricePerLesson)}, ${sqlInteger(opt.pricePerLessonUnder21Cents)})`,
			);
		}
	}

	if (optionTuples.length === 0) {
		return `  RAISE NOTICE 'public.lesson_type_options: 0 row(s) inserted (nothing to import)';
`;
	}

	return `  -- Lesson type options (latest startdate per duration+frequency; price as-is)
  INSERT INTO public.lesson_type_options (
    lesson_type_id,
    duration_minutes,
    frequency,
    price_per_lesson,
    price_per_lesson_under_21_cents
  )
  SELECT lt.id, opt.duration_minutes, opt.frequency, opt.price_per_lesson, opt.price_per_lesson_under_21_cents
  FROM (VALUES
${optionTuples.join(',\n')}
  ) AS opt(lesson_type_name, duration_minutes, frequency, price_per_lesson, price_per_lesson_under_21_cents)
  INNER JOIN public.lesson_types lt ON lt.name = opt.lesson_type_name
  WHERE NOT EXISTS (
    SELECT 1 FROM public.lesson_type_options lto
    WHERE lto.lesson_type_id = lt.id
      AND lto.duration_minutes = opt.duration_minutes
      AND lto.frequency = opt.frequency
      AND lto.price_per_lesson = opt.price_per_lesson
  );
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'public.lesson_type_options: % row(s) inserted (existing skipped)', n;
`;
}

/** Build idempotent bootstrap-compatible SQL for lesson types + options. */
export function buildCoursesSql(rows: CourseSqlRow[]): string {
	if (rows.length === 0) {
		return '-- No courses to import\n';
	}

	return `-- Generated by import/courses — apply manually to the target database.
DO $$
DECLARE
  n integer;
BEGIN
${buildLessonTypesInsert(rows)}
${buildLessonTypeOptionsInsert(rows)}END $$;
`;
}
