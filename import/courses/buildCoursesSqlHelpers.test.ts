import { describe, expect, it } from 'bun:test';
import { buildCoursesSql } from './buildCoursesSqlHelpers';
import type { CourseSqlRow } from './types';

const sampleRow: CourseSqlRow = {
	mongoOid: 'oid-1',
	lessonTypeId: '11111111-1111-1111-1111-111111111111',
	name: '09 Gitaar',
	costCenter: '8310',
	isDuoLesson: false,
	isGroupLesson: false,
	icon: 'LuGuitar',
	color: '#FF9500',
	optionWarnings: [],
	options: [
		{
			durationMinutes: 30,
			frequency: 'weekly',
			pricePerLesson: 73.38,
			pricePerLessonUnder21Cents: 1950,
			startDate: '2026-09-01',
			skippedUnknownOid: null,
		},
	],
};

describe('buildCoursesSql', () => {
	it('emits idempotent lesson_types and lesson_type_options inserts', () => {
		const sql = buildCoursesSql([sampleRow]);
		expect(sql).toContain('Generated by import/courses — apply manually to the target database.');
		expect(sql).toContain('INSERT INTO public.lesson_types');
		expect(sql).toContain("'09 Gitaar'");
		expect(sql).toContain('is_duo_lesson');
		expect(sql).toContain('INSERT INTO public.lesson_type_options');
		expect(sql).toContain('73.38');
		expect(sql).toContain('1950');
		expect(sql).toContain('WHERE NOT EXISTS');
	});

	it('returns a comment when there are no rows', () => {
		expect(buildCoursesSql([])).toBe('-- No courses to import\n');
	});
});
