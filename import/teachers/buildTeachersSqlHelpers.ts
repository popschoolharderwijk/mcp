import { dedupeImportRowsByUserId } from '../shared/dedupeImportRowsByUserIdHelpers';
import { sqlBoolean, sqlDate, sqlUuid } from '../shared/sqlEscapeHelpers';
import type { MappedTeacherRow } from './types';

export type TeacherSqlRow = MappedTeacherRow & { userId: string };

/** Role-only SQL: public.teachers (auth user must already exist from profiles.sql). */
export function buildTeachersSql(rows: TeacherSqlRow[]): string {
	if (rows.length === 0) {
		return '-- No teachers to import\n';
	}

	const deduped = dedupeImportRowsByUserId(rows, (existing, duplicate) => ({
		...existing,
		cocIssuedOn: existing.cocIssuedOn ?? duplicate.cocIssuedOn,
	}));

	const valueTuples = deduped.map((row) => `    (${sqlUuid(row.userId)}, ${sqlDate(row.cocIssuedOn)})`).join(',\n');

	return `-- Generated by import/teachers — public.teachers only (run after profiles.sql).
DO $$
DECLARE
  n integer;
BEGIN
  CREATE TEMP TABLE mongo_import_teachers (
    id UUID PRIMARY KEY,
    coc_issued_on DATE
  ) ON COMMIT DROP;

  INSERT INTO mongo_import_teachers (id, coc_issued_on)
  VALUES
${valueTuples};

  INSERT INTO public.teachers (user_id, coc_issued_on, is_active)
  SELECT id, coc_issued_on, ${sqlBoolean(true)}
  FROM mongo_import_teachers
  ON CONFLICT (user_id) DO UPDATE SET
    coc_issued_on = EXCLUDED.coc_issued_on,
    is_active = EXCLUDED.is_active,
    updated_at = now();
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'public.teachers: % row(s) upserted', n;
END $$;
`;
}
