import { describe, expect, it } from 'bun:test';
import { buildAgreementsCoursesSql } from './buildAgreementsCoursesSqlHelpers';
import type { AgreementCourseSqlRow } from './types';

const sampleRow: AgreementCourseSqlRow = {
	mongoOid: 'agreement-oid',
	agreementId: 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa',
	studentUserId: 'bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb',
	teacherUserId: 'cccccccc-cccc-cccc-cccc-cccccccccccc',
	lessonTypeId: 'dddddddd-dddd-dddd-dddd-dddddddddddd',
	durationMinutes: 30,
	frequency: 'weekly',
	pricePerLesson: 73.38,
	dayOfWeek: 2,
	startTime: '19:35:52',
	startDate: '2024-08-26',
	endDate: null,
	isActive: true,
	notes: 'CA10663\nDesc',
	signupSource: 'staff',
	paymentMethod: 'sepa',
	monthlyAmountCents: 4250,
	duoPairId: null,
	synthesizeLessonTypeOption: false,
	optionWarning: null,
};

describe('buildAgreementsCoursesSql', () => {
	it('emits an idempotent lesson_agreements insert', () => {
		const sql = buildAgreementsCoursesSql([sampleRow]);
		expect(sql).toContain('Generated by import/agreements_courses — apply manually to the target database.');
		expect(sql).toContain('INSERT INTO public.lesson_agreements');
		expect(sql).not.toContain('Synthesized lesson_type_options');
		expect(sql).toContain("'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa'::uuid");
		expect(sql).toContain("'weekly'::public.lesson_frequency");
		expect(sql).toContain('73.38');
		expect(sql).toContain('NULL::date');
		expect(sql).toContain('NULL::uuid');
		expect(sql).toContain('duo_pair_id');
		expect(sql).toContain('WHERE NOT EXISTS');
		expect(sql).toContain("RAISE NOTICE 'public.lesson_agreements:");
	});

	it('emits duo_pair_id when the agreement is for a duo lesson type', () => {
		const sql = buildAgreementsCoursesSql([{ ...sampleRow, duoPairId: 'ffffffff-ffff-ffff-ffff-ffffffffffff' }]);
		expect(sql).toContain("'ffffffff-ffff-ffff-ffff-ffffffffffff'::uuid");
	});

	it('emits synthesized lesson_type_options before agreements when needed', () => {
		const sql = buildAgreementsCoursesSql([
			{
				...sampleRow,
				durationMinutes: 45,
				frequency: 'biweekly',
				pricePerLesson: 16.34,
				synthesizeLessonTypeOption: true,
				optionWarning: 'synth',
			},
			{
				...sampleRow,
				mongoOid: 'agreement-oid-2',
				agreementId: 'eeeeeeee-eeee-eeee-eeee-eeeeeeeeeeee',
				durationMinutes: 45,
				frequency: 'biweekly',
				pricePerLesson: 16.34,
				synthesizeLessonTypeOption: true,
				optionWarning: 'synth',
			},
		]);

		expect(sql).toContain('Synthesized lesson_type_options');
		expect(sql).toContain('INSERT INTO public.lesson_type_options');
		expect(sql).toContain("'dddddddd-dddd-dddd-dddd-dddddddddddd'::uuid");
		expect(sql).toContain("'biweekly'::public.lesson_frequency");
		expect(sql).toContain('16.34');
		expect(sql).toContain('1634');
		expect(sql.indexOf('lesson_type_options')).toBeLessThan(sql.indexOf('lesson_agreements'));
		const optionsSection = sql.slice(0, sql.indexOf('INSERT INTO public.lesson_agreements'));
		expect(optionsSection.split("'dddddddd-dddd-dddd-dddd-dddddddddddd'::uuid")).toHaveLength(2);
	});

	it('returns a comment when there are no rows', () => {
		expect(buildAgreementsCoursesSql([])).toBe('-- No agreements_courses to import\n');
	});
});
