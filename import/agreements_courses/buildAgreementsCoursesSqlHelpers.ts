import { sqlBoolean, sqlDate, sqlInteger, sqlNumber, sqlString, sqlTime, sqlUuid } from '../shared/sqlEscapeHelpers';
import type { AgreementCourseSqlRow } from './types';

function buildSynthesizedOptionsInsert(rows: AgreementCourseSqlRow[]): string {
	const seen = new Set<string>();
	const tuples: string[] = [];

	for (const row of rows) {
		if (!row.synthesizeLessonTypeOption) continue;
		const key = `${row.lessonTypeId}:${row.durationMinutes}:${row.frequency}:${row.pricePerLesson}`;
		if (seen.has(key)) continue;
		seen.add(key);
		const under21Cents = Math.round(row.pricePerLesson * 100);
		tuples.push(
			`  (${sqlUuid(row.lessonTypeId)}, ${sqlInteger(row.durationMinutes)}, '${row.frequency}'::public.lesson_frequency, ${sqlNumber(row.pricePerLesson)}, ${sqlInteger(under21Cents)})`,
		);
	}

	if (tuples.length === 0) {
		return '';
	}

	return `-- Synthesized lesson_type_options (agreement durationfreq missing from course frequency_mnd_prices)
INSERT INTO public.lesson_type_options (
  lesson_type_id,
  duration_minutes,
  frequency,
  price_per_lesson,
  price_per_lesson_under_21_cents
)
SELECT
  v.lesson_type_id,
  v.duration_minutes,
  v.frequency,
  v.price_per_lesson,
  v.price_per_lesson_under_21_cents
FROM (VALUES
${tuples.join(',\n')}
) AS v(lesson_type_id, duration_minutes, frequency, price_per_lesson, price_per_lesson_under_21_cents)
WHERE NOT EXISTS (
  SELECT 1 FROM public.lesson_type_options lto
  WHERE lto.lesson_type_id = v.lesson_type_id
    AND lto.duration_minutes = v.duration_minutes
    AND lto.frequency = v.frequency
    AND lto.price_per_lesson = v.price_per_lesson
);

`;
}

function buildLessonAgreementsInsert(rows: AgreementCourseSqlRow[]): string {
	const tuples = rows
		.map((row) => {
			return `  (${sqlUuid(row.agreementId)}, ${sqlUuid(row.studentUserId)}, ${sqlUuid(row.teacherUserId)}, ${sqlUuid(row.lessonTypeId)}, ${sqlInteger(row.durationMinutes)}, '${row.frequency}'::public.lesson_frequency, ${sqlNumber(row.pricePerLesson)}, ${sqlInteger(row.dayOfWeek)}, ${sqlTime(row.startTime)}, ${sqlDate(row.startDate)}, NULL, ${sqlBoolean(row.isActive)}, ${sqlString(row.notes)}, ${sqlString(row.signupSource)}, ${sqlString(row.paymentMethod)}, ${sqlInteger(row.monthlyAmountCents)})`;
		})
		.join(',\n');

	return `INSERT INTO public.lesson_agreements (
  id,
  student_user_id,
  teacher_user_id,
  lesson_type_id,
  duration_minutes,
  frequency,
  price_per_lesson,
  day_of_week,
  start_time,
  start_date,
  end_date,
  is_active,
  notes,
  signup_source,
  payment_method,
  monthly_amount_cents
)
SELECT
  v.id,
  v.student_user_id,
  v.teacher_user_id,
  v.lesson_type_id,
  v.duration_minutes,
  v.frequency,
  v.price_per_lesson,
  v.day_of_week,
  v.start_time,
  v.start_date,
  v.end_date,
  v.is_active,
  v.notes,
  v.signup_source,
  v.payment_method,
  v.monthly_amount_cents
FROM (VALUES
${tuples}
) AS v(
  id,
  student_user_id,
  teacher_user_id,
  lesson_type_id,
  duration_minutes,
  frequency,
  price_per_lesson,
  day_of_week,
  start_time,
  start_date,
  end_date,
  is_active,
  notes,
  signup_source,
  payment_method,
  monthly_amount_cents
)
WHERE NOT EXISTS (SELECT 1 FROM public.lesson_agreements WHERE lesson_agreements.id = v.id);
`;
}

/** Build idempotent SQL for synthesized options + lesson_agreements. */
export function buildAgreementsCoursesSql(rows: AgreementCourseSqlRow[]): string {
	if (rows.length === 0) {
		return '-- No agreements_courses to import\n';
	}

	return `-- Generated by import/agreements_courses — apply manually to the target database.
${buildSynthesizedOptionsInsert(rows)}${buildLessonAgreementsInsert(rows)}`;
}
