import { SEED_ENCRYPTED_PASSWORD } from '../shared/seedAuthPassword';
import { sqlString, sqlUuid } from '../shared/sqlEscapeHelpers';
import type { ProfileSqlRow } from './types';

function buildPeopleValues(rows: ProfileSqlRow[]): string {
	return rows
		.map((row) => {
			return `    (${sqlUuid(row.userId)}, ${sqlString(row.email)}, ${sqlString(row.firstName)}, ${sqlString(row.lastName)}, ${sqlString(row.phoneNumber)}, ${sqlString(row.streetName)}, ${sqlString(row.houseNumber)}, ${sqlString(row.postalCode)}, ${sqlString(row.city)}, ${sqlString(row.countryCode)})`;
		})
		.join(',\n');
}

/** Build idempotent SQL for auth.users, identities, and public.profiles only. */
export function buildProfilesSql(rows: ProfileSqlRow[]): string {
	if (rows.length === 0) {
		return '-- No profiles to import\n';
	}

	return `-- Generated by import/profiles — auth users + public.profiles only (roles in students.sql / teachers.sql).
DO $$
DECLARE
  n integer;
BEGIN
  CREATE TEMP TABLE mongo_import_profiles (
    id UUID PRIMARY KEY,
    email TEXT NOT NULL,
    first_name TEXT,
    last_name TEXT,
    phone_number TEXT,
    street_name TEXT,
    house_number TEXT,
    postal_code TEXT,
    city TEXT,
    country_code TEXT NOT NULL DEFAULT 'NL'
  ) ON COMMIT DROP;

  INSERT INTO mongo_import_profiles (
    id, email, first_name, last_name, phone_number, street_name, house_number,
    postal_code, city, country_code
  )
  VALUES
${buildPeopleValues(rows)};

  INSERT INTO auth.users (
    id,
    instance_id,
    aud,
    role,
    email,
    encrypted_password,
    email_confirmed_at,
    raw_app_meta_data,
    raw_user_meta_data,
    created_at,
    updated_at,
    confirmation_token,
    email_change,
    email_change_token_new,
    recovery_token
  )
  SELECT
    id,
    '00000000-0000-0000-0000-000000000000',
    'authenticated',
    'authenticated',
    email,
    '${SEED_ENCRYPTED_PASSWORD}',
    now(),
    '{"provider":"email","providers":["email"]}',
    json_build_object(
      'first_name', first_name,
      'last_name', last_name
    ),
    now(),
    now(),
    '',
    '',
    '',
    ''
  FROM mongo_import_profiles
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    raw_user_meta_data = EXCLUDED.raw_user_meta_data,
    updated_at = now();
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'auth.users: % row(s) upserted', n;

  INSERT INTO auth.identities (
    id,
    user_id,
    provider_id,
    provider,
    identity_data,
    last_sign_in_at,
    created_at,
    updated_at
  )
  SELECT
    id,
    id,
    email,
    'email',
    json_build_object(
      'sub', id::text,
      'email', email,
      'email_verified', true,
      'provider', 'email'
    ),
    now(),
    now(),
    now()
  FROM mongo_import_profiles
  ON CONFLICT (id) DO NOTHING;
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'auth.identities: % row(s) inserted', n;

  UPDATE public.profiles p
  SET
    first_name = t.first_name,
    last_name = t.last_name,
    phone_number = t.phone_number,
    email = t.email,
    street_name = t.street_name,
    house_number = t.house_number,
    postal_code = t.postal_code,
    city = t.city,
    country_code = t.country_code
  FROM mongo_import_profiles t
  WHERE p.user_id = t.id;
  GET DIAGNOSTICS n = ROW_COUNT;
  RAISE NOTICE 'public.profiles: % row(s) updated', n;
END $$;
`;
}
